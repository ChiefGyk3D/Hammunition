"""Kiwix books: the catalog's allow-list, its pins, and the station's choice.  D-065.

Three files meet here:

* ``catalog/data/kiwix-books.yaml``, **hand-written**: which books the catalog
  offers, and each one's licence line. It has to be hand-written because the
  ZIM does not say: of nine read on 2026-09-29, one carried a ``License``
  metadata entry. A book this list does not name has no known licence to
  print before the confirmation (D-049 rule 2), so choosing it is refused.
* ``catalog/data/kiwix-pins.yaml``, **generated** by
  ``scripts/gen_kiwix_pins.py`` from Kiwix's ``library_zim.xml`` and each
  book's ``.meta4``: the dated file, its exact size and its sha256. Nothing
  Kiwix publishes is signed; the pin freezes what TLS to download.kiwix.org
  delivered on the day it was generated.
* station config's ``reference_books``: the ids the operator chose.

A book's id is Kiwix's own file stem without the date: ``<name>_<flavour>``,
or the bare name for a book published in one flavour
(``ham.stackexchange.com_en_all``). The files are
``<id>_<YYYY-MM>.zim`` under ``https://download.kiwix.org/zim/<category>/``.

Kiwix keeps only the two newest dated files of a book, so a pin dies about
two publications after it is made. A pin that is gone is an error naming the
regeneration, never a quiet move to the newer file: the newer file has a hash
nobody here has measured.
"""

