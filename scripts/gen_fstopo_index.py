"""Generate the Forest Service FSTopo quad index, and grow its pins.
D-068, amended 2026-10-01.

``catalog/data/fstopo-quads.txt`` names every FSTopo 7.5-minute quad in the
Forest Service's GTAC index, one per line:

    <south> <west> <north> <east> <secoord> <vintage> <ST> <cell name>

so the plan can choose a region's sheets with no network. The input is the
ArcGIS feature layer ``FSTopo_Index_GTAC`` (USDA Forest Service, Geospatial
Technology and Applications Center): each feature's polygon gives the box,
``secoord`` names the sheet to the raster gateway, ``vintage`` its edition
(a two-digit year, 0 where the layer gives none: 6,560 of 18,188 on
2025-08-08), ``primary_state`` and ``cell_name`` its state and name. The
header records the layer's ``dataLastEditDate`` (D-031: an input's date,
never the day this ran). A feature with no secoord, no name or no state is
left out and counted.

The Forest Service publishes **no checksum** for a sheet: the gateway's
ETag is Apache's inode-size-mtime. ``catalog/data/fstopo-pins.yaml`` holds
the sha256 and size of the sheets the maintainer has measured, grown one
sheet at a time with ``--pin``, which downloads the sheet; it starts empty.
A sheet with no pin is fetched unverified, and the plan says so by name.

    scripts/gen_fstopo_index.py --fetch                       # about 19 pages
    scripts/gen_fstopo_index.py --save-features F             # save the pages
    scripts/gen_fstopo_index.py --fetch --features F          # from saved pages
    scripts/gen_fstopo_index.py --pin SECOORD [SECOORD ...]   # downloads each sheet
    scripts/gen_fstopo_index.py --check [--offline]

``--check --offline`` checks the index's shape and the pins file. Plain
``--check`` also fetches the layer again and exits 1 naming each carried
quad that is gone or whose box changed; a new quad or a new vintage is
counted, not failed.
"""

