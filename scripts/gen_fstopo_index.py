import yaml

REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT / "src"))

from hammunition.fstopo import (  # noqa: E402
    FsQuad,
    FstopoError,
    GatewayProbe,
    load_pins,
    parse_index,
    parse_row,
    render_row,
)

INDEX = REPO_ROOT / "catalog" / "data" / "fstopo-quads.txt"
PINS = REPO_ROOT / "catalog" / "data" / "fstopo-pins.yaml"
LAYER = (
    "https://services1.arcgis.com/gGHDlz6USftL5Pau/arcgis/rest/services/"
    "FSTopo_Index_GTAC/FeatureServer/0"
)
FIELDS = "secoord,cell_name,primary_state,vintage"
PAGE = 1000
TIMEOUT = 60.0
GENERATED_MARK = "GENERATED by scripts/gen_fstopo_index.py"
_COUNTS = re.compile(r"# quads: (\d+); left out, no secoord, name or state: (\d+)")
_EDITED = re.compile(r"# index: FSTopo_Index_GTAC, last edited (\d{4}-\d{2}-\d{2})")

HEADER = """\
# SPDX-FileCopyrightText: Copyright (C) 2026 Renegade Penguin LLC
# SPDX-License-Identifier: CC0-1.0

# {mark} --fetch. Do not edit by hand.
#
# Every Forest Service FSTopo 7.5-minute quad in the GTAC index (US federal
# work, public domain), one per line: south west north east (degrees, NAD83),
# secoord (the sheet's number at the raster gateway), vintage (the index's
# edition, a two-digit year; 0 where it gives none), primary state, and the
# cell name. A region's sheets are those whose box
# overlaps a 1/8-degree cell its outline touches. The Forest Service
# publishes no checksum; a sheet with a row in fstopo-pins.yaml is checked by
# that sha256, and any other is fetched unverified, the plan saying so.
#
# index: FSTopo_Index_GTAC, last edited {edited}
# quads: {total}; left out, no secoord, name or state: {missing}
#
# Regenerate: scripts/gen_fstopo_index.py --fetch
# Check:      scripts/gen_fstopo_index.py --check (the layer again, no sheet)
"""

PINS_HEADER = """\
# SPDX-FileCopyrightText: Copyright (C) 2026 Renegade Penguin LLC
# SPDX-License-Identifier: CC0-1.0

# {mark} --pin. Do not edit by hand.
#
# The FSTopo sheets whose sha256 the maintainer measured, by secoord. The
# Forest Service publishes no checksum; a sheet listed here is checked
# against this sha256 and size ("sha256, pinned by Hammunition"), and any
# other is fetched unverified, the plan saying so by name. A pin goes stale
# when the Forest Service re-issues the sheet: the plan then refuses it by
# name, and --pin measures it again.
"""


