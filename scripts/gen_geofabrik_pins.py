"""Generate catalog/data/geofabrik-pins.yaml: sha256 pins for Geofabrik extracts.

Geofabrik publishes an MD5 beside every extract and nothing stronger. For the
regions listed in ``REGIONS`` Hammunition carries its own sha256, measured
here: each region's current yearly snapshot (``<region>-YY0101.osm.pbf``) and
current monthly snapshot (``<region>-YYMM01.osm.pbf``) is streamed, hashed
and sized, and the bytes are discarded. Nothing is kept or mirrored.

A full pass downloads about 10 GB (the 50 US states and DC, twice), so it is
run on the maintainer's machine, never in CI and never in the test suite::

    scripts/gen_geofabrik_pins.py                      # every region
    scripts/gen_geofabrik_pins.py --region north-america/us/vermont
    scripts/gen_geofabrik_pins.py --check              # HEAD sizes only

``--region`` replaces only the named regions' rows and keeps every other
row. A region must be in ``REGIONS`` first: adding one is a line here and a
regeneration, so the pinned set is always what this file says it is.

``--check`` downloads nothing. It asks each pinned URL for its ``HEAD`` and
exits 1 naming every pin whose URL no longer answers 200 or whose
``Content-Length`` is not the pinned size. Geofabrik keeps about three monthly
snapshots, so a monthly pin ages out within a quarter; the weekly CI job runs
``--check`` and goes red when one does, with the command to regenerate. A
dated file never redirects, so a 3xx is a failure too: whatever it points at
is not the file that was hashed.

The region names are Geofabrik's own download paths under
``north-america/us/``, lowercase and hyphenated, as its region index
(https://download.geofabrik.de/index-v1.json) names them. They were written
here literally, not fetched; a wrong one fails the first real pass by URL.
"""

from __future__ import annotations

import argparse
import hashlib
import re
import sys
import urllib.error
import urllib.request
from collections.abc import Callable, Iterable, Iterator, Sequence
from datetime import date
from pathlib import Path
from typing import Any

import yaml

REPO_ROOT = Path(__file__).resolve().parent.parent
OUT = REPO_ROOT / "catalog" / "data" / "geofabrik-pins.yaml"
BASE = "https://download.geofabrik.de"
REGION_PATTERN = re.compile(r"[a-z0-9-]+(/[a-z0-9-]+)*")
SNAPSHOT_PATTERN = re.compile(r"\d{6}")
SHA256_PATTERN = re.compile(r"[0-9a-f]{64}")
GENERATED_MARK = "GENERATED by scripts/gen_geofabrik_pins.py"
TIMEOUT = 60.0
CHUNK = 1024 * 1024

